"""Builder and constants for the static, seven-level global wealth tree."""
from __future__ import annotations

# ---------------------------------------------------------------------------
# Geography. Four buckets whose shares follow the UBS 2025 end-2024 regional
# split of the 56-market sample (37% / 23% / 21% / 18%): North America;
# Western + Eastern Europe; Greater China; and the rest of the report's
# markets (Southeast Asia, Oceania, Latin America, Middle East & Africa).
# Each is (name, share of parent, nominal growth %/yr). The shares are the
# end-2024 mix — the ten-year history uses the report's measured regional
# record instead (see economy_series).
# ---------------------------------------------------------------------------

REGIONS = (
    ("United States & Canada", 37, 5.0),
    ("Europe", 23, 3.6),
    ("China", 21, 4.4),
    ("Asia-Pacific & rest", 18, 5.4),
)

REGION_NAMES = tuple(r[0] for r in REGIONS)
REGION_SHARES = tuple(r[1] for r in REGIONS)
REGION_GROWTH = tuple(r[2] for r in REGIONS)

# The world's own growth before any branch rates are blended: UBS sees
# close to 5%/yr for the rest of the decade; the long-run real record
# (3.4%) plus ~2% inflation lands in the same place.
WORLD_GROWTH = 4.8


def n(name, share, *children, note=None, g=None, regions=None, rg=None):
    """One authored node.

    ``share`` is a percentage of the parent. ``g`` is a nominal annual
    growth rate that descendants inherit unless they set their own.
    ``regions`` / ``rg`` override the geography split for this branch.
    """
    return {
        "name": name,
        "share": share,
        "note": note,
        "g": g,
        "regions": regions,
        "rg": rg,
        "kids": list(children),
    }


def _normalize(kids):
    """Scale a sibling set to whole percentages that add up to 100."""
    total = sum(k["share"] for k in kids)
    if total == 100:
        return
    if total <= 0:
        raise ValueError("sibling shares must be positive")
    exact = [k["share"] * 100 / total for k in kids]
    out = [int(x) for x in exact]
    short = 100 - sum(out)
    order = sorted(
        range(len(kids)), key=lambda i: exact[i] - out[i], reverse=True
    )
    for i in order[:short]:
        out[i] += 1
    for k, s in zip(kids, out):
        k["share"] = s


def _expand(node, depth, names, shares, growth):
    """Attach the region leaves at level 7 and normalize every sibling set."""
    if node["regions"] is not None:
        shares = node["regions"]
    if node["rg"] is not None:
        growth = node["rg"]

    if not node["kids"]:
        if depth != 6:
            raise ValueError(f"branch ends at level {depth}: {node['name']!r}")
        mean = sum(s * g for s, g in zip(shares, growth)) / 100
        node["kids"] = [
            {
                "name": name,
                "share": share,
                "note": None,
                "g": None,
                "tilt": round(g - mean, 2),
                "kids": [],
                "regions": None,
                "rg": None,
            }
            for name, share, g in zip(names, shares, growth)
            if share > 0
        ]
        return

    if depth >= 6:
        raise ValueError(f"too deep: {node['name']!r} at level {depth}")
    for k in node["kids"]:
        _expand(k, depth + 1, names, shares, growth)
    _normalize(node["kids"])


def _blend(node):
    """Give every node the share-weighted growth of its parts.

    Region leaves carry a ``tilt`` — how much faster or slower that
    region grows than the world average for this kind of asset — so the
    authored rate of the leaf survives while geography still differs.
    """
    if not node["kids"]:
        node["g"] = round(float(node["g"]) + float(node.get("tilt") or 0), 1)
        return node["g"]
    total = 0.0
    for k in node["kids"]:
        total += k["share"] * _blend(k)
    node["g"] = round(total / 100, 1)
    return node["g"]


def _inherit(node, inherited):
    """Fill in growth top-down: a branch inherits the rate above it."""
    if node["g"] is None:
        node["g"] = inherited
    for k in node["kids"]:
        _inherit(k, node["g"])


def expand(root):
    """Turn the authored tree into the shipped one: regions, sums, growth."""
    _expand(root, 0, REGION_NAMES, REGION_SHARES, REGION_GROWTH)
    _inherit(root, WORLD_GROWTH)
    _blend(root)
    return root


